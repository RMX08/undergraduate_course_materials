# 网页给出的 64 字节密文
cipher = [
    0x19,0x3b,0x76,0x05,0x6c,0x55,0x31,0x0e,
    0x27,0x30,0x32,0xffffff88,0x1a,0xffffffaa,0x45,0x44,
    0x5a,0x78,0x79,0x55,0x3b,0x6c,0x08,0x37,
    0x15,0x50,0x03,0xffffffb8,0x23,0xffffffee,0x01,0x00,
    0x04,0x26,0x68,0x0f,0x65,0x38,0x5c,0x63,
    0x15,0x1b,0x44,0xfffffff9,0x36,0xfffffffb,0x14,0x15,
    0x08,0x79,0x64,0x17,0x2c,0x71,0x15,0x2a,
    0x57,0x16,0x5c,0xffffffb6,0x2c,0xffffffe1,0x0e,0x0f
]

# 统一转换为真正的单字节
cipher = [x & 0xff for x in cipher]

#  IDA 中的 16 字节 key
keys = [
    0x7f, 0x12, 0x2c, 0x4a,
    0x0b, 0x5d, 0x64, 0x3f,
    0x45, 0x23, 0x67, 0x89,
    0xAB, 0xCD, 0xEF, 0x01
]

# 逆 rolling XOR
# 加密：
# C[0] = T[0] ^ key[0]
# C[k] = T[k] ^ key[k % 16] ^ C[k-1]
# 解密：
# M[0] = C[0] ^ key[0]
# M[k] = C[k] ^ key[k % 16] ^ C[k-1]
M = [0] * 64

M[0] = cipher[0] ^ keys[0]

for k in range(1, 64):
    M[k] = (cipher[k] ^ keys[k % 16] ^ cipher[k - 1])

# 逆矩阵转置
# 转置：flag[8*i+j] = M[8*j+i]

flag = [0] * 64

for i in range(8):
    for j in range(8):
        flag[8 * i + j] = M[8 * j + i]

# 输出结果
# print(bytes(flag))

# 去除结尾的 \x00
print(bytes(flag).rstrip(b'\x00').decode('utf-8', errors='replace'))